#include <stdio.h>
#include <string.h>
#include <stdlib.h>

#include "calc.h"
#include "decode.h"

int main(
    int argc, // количество аргументов
    char *argv[] // набор аргументов
) { 
    // Проверяем минимальное кол-во аргументов. ["./main", "1", "+", "1", "-k", "0"] - минимальный запуск на 6 аргументов.
    // Проверяем что, переданные операнды это тройки ["число", "операнд", "число"]. Выкидываем из argc 3 лишних аргумента [""./main", "-k", "0"] и делим на 3. Ожидается остаток от деления 3.
    if (argc < 6 || (argc - 3) % 3 != 0) {
        fprintf(stderr, "Ошибка: неверное количество аргументов\n");
        return 1;
    }

    // Проверяем что "-k" стоит на предпоследнем месте
    // strcmp (string compare - сравнение строк). Передаем в метод strcmp({Предпоследний аргумент из строки терминала}, {Ожидаемый элемент})
    // strcmp вернет 0, если argv[argc - 2] равен "-k"
    // strcmp это отдельный библиотечный метод. Значит его нужно импортировать #include <string.h>
    if (strcmp(argv[argc - 2], "-k") != 0) {
        fprintf(stderr, "Ошибка: флаг -k должен стоять после всех выражений\n");
        return 1;
    }
    
    // Проверяем что -k передали целым числом через метод is_number, который определили в файле calc.h, и подключили сюда #include "calc.h"
    if (!is_number(argv[argc - 1])) {
        fprintf(stderr, "Ошибка: ключ \"%s\" не является целым числом\n", argv[argc - 1]);
        return 1;
    }

    // Проверяем тройки ["операнд", "оператор", "операнд"]
    int triplesCount = (argc - 3) / 3; // Количество троек переданых в аргументах. Вычислятся: Количество всех аргументов минус 3 ("./main", "-k", "0")
    // malloc — выделяет память в куче на массив, куда складываются результаты вычислений. 
    // Каждый элемент — ответ одной тройки ["1", "+", "1"]
    // Результат вычисления выражения в int. 
    // Значит память нужно выделить так: количество ответов * размер int в байтах. Обычно 4, но стандарт не фиксирует — на разных платформах может быть 2, 4, 8
    int *answers = malloc(triplesCount * sizeof(int)); 
    if (!answers) { // malloc может не выделить память, если в системе его нет в запрошеном обьеме, напрмиер
        fprintf(stderr, "Ошибка выделения памяти\n");
        return 1;
    }

    // Проверяем тройки ["операнд", "оператор", "операнд"] итерируясь по из количеству, которое узнали на прошлом шаге
    for (int t = 0; t < triplesCount; t++) {
        // Вычисляем индекс начала тройки в массиве аргументов
        // Для первой тройки индекс начала будет равен 1 - первый элемент массива
        // ["./main", "1", "+", "1", "3", "+" ,"2" ...]
        //      0.     1.   2.   3.   4.   5.   6.
        int tripleStart = 1 + 3 * t; 
        int left; // сюда потом кладётся левый операнд
        int right; // cюда кладётся правый операнд

        // Проверяем что левый - число. Метод is_number подключил из "calc.h" на прошлом шаге
        if (!is_number(argv[tripleStart])) {
            fprintf(stderr, "Ошибка: '%s' не число (левый операнд №%d)\n",
                    argv[tripleStart], t + 1); // t + 1 это счетчик цикла понятный для человека. Программа отсчитывает с 0, а человек с 1
            // При ошибке освобождаем память выделеную через malloc
            free(answers);
            return 1;
        }

        // Проверяем средний (tripleStart + 1) позиция, является оператором. Метод is_operator подключил из "calc.h"
        if (!is_operator(argv[tripleStart + 1])) {
            fprintf(stderr, "Ошибка: недопустимый оператор '%s' (выражение №%d)\n",
                    argv[tripleStart + 1], t + 1);
            free(answers); 
            return 1;
        }

        // Проверяем что правый (tripleStart + 2) - число. Метод is_number подключил из "calc.h" на прошлом шаге
        if (!is_number(argv[tripleStart + 2])) {
            fprintf(stderr, "Ошибка: '%s' не число (правый операнд №%d)\n",
                    argv[tripleStart + 2], t + 1);
            free(answers);
            return 1;
        }


        // atoi - ASCII to integer, функция из <stdlib.h>, превращает строку в int.
        // "41" → 41
        left  = atoi(argv[tripleStart]);
        right = atoi(argv[tripleStart + 2]);

        // Проверяем деление на ноль
        // argv[tripleStart + 1][0] == '%' - средний элемент тройки = '%'. 
        // Пишем [0] потому что берем первый символ из строки, которой является средний элемент тройки (операнд).
        if (argv[tripleStart + 1][0] == '%' && right == 0) {
            fprintf(stderr, "Ошибка: деление на ноль (выражение №%d)\n", t + 1);
            free(answers);
            return 1;
        }

        // Методом calculate вычисляем результат тройки, и по индексу итерации кладем его в набор с результатами для дальнейшего вывода.
        // calculate определен в "calc.h"
        answers[t] = calculate(left, argv[tripleStart + 1][0], right);
    }

    // Это тот самый -k, значение которого последним аргументом передаем
    int k = atoi(argv[argc - 1]); 

    // Выделяем память под результирующий текст. Размер +1 потому что в конце строки добавляется '\0' для обозначения конца строки
    char *text = malloc(triplesCount + 1); 
    // Вызываем метод decode из "decode.h", для того чтоб превратить результаты вычисления в строку.
    // decode записывает результаты вычисления в переданную ему переменную text
    decode(answers, triplesCount, k, text);
    // Вызываем print_results для печати результатов.
    print_results(answers, triplesCount, text);

    free(text);
    free(answers);

    return 0;
}
