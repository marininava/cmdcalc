#include <stdio.h>

int main(
    int argc, // количество аргументов
    char *argv[] // набор аргументов
) { 
    if (argc < 6 || (argc - 3) % 3 != 0) {
        // Проверяем минимальное кол-во аргументов. ["./main", "1", "+", "1", "-k", "0"] - минимальный запуск на 6 аргументов.
        // Проверяем что, переданные операнды это тройки ["число", "операнд", "число"]. Выкидываем из argc 3 лишних аргумента [""./main", "-k", "0"] и делим на 3. Ожидается остаток от деления 3.
        fprintf(stderr, "Ошибка: неверное количество аргументов\n");
        return 1;
    }
    
    return 0;
}