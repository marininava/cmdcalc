#include <stdio.h>   // подключение библиотеки ввода-вывода

// Принимаем аргументы из терминала при запуске программы.
int main(
    int argc, // количество аргументов
    char *argv[] // набор аргументов
) {     
    // Вывести все аргументы, которые программа приняла
    for (int i = 0; i < argc; i++) {
        // "argv[%d] = %s\n" - шаблон строки
        // %d - подсавляется i. %d - потому что число (digit)
        // %s - подставляется argv[i]. %s - потому что строка, даже если передали число
        // аргументы передаются поочередно
        // Проверить запуск - скомпилировать, запустить ./main firstArg secongArg
        printf("argv[%d] = %s\n", i, argv[i]);
    }
    return 0;
}