#include <stdio.h>
#include <string.h>

int main(
    int argc, // количество аргументов
    char *argv[] // набор аргументов
) { 
    if (argc < 6 || (argc - 3) % 3 != 0) {
        // Проверяем минимальное кол-во аргументов. ["./main", "1", "+", "1", "-k", "0"] - минимальный запуск на 6 аргументов.
        // Проверяем что, переданные операнды это тройки ["число", "операнд", "число"]. Выкидываем из argc 3 лишних аргумента [""./main", "-k", "0"] и делим на 3. Ожидается остаток от деления 3.
        fprintf(stderr, "Ошибка: неверное количество аргументов\n");
        return 1;
    }

    // Проверяем что "-k" стоит на предпоследнем месте
    // strcmp (string compare - сравнение строк). Передаем в метод strcmp({Предпоследний аргумент из строки терминала}, {Ожидаемый элемент})
    // strcmp вернет 0, если argv[argc - 2] равен "-k"
    // strcmp это отдельный библиотечный метод. Значит его нужно импортировать #include <string.h>
    if (strcmp(argv[argc - 2], "-k") != 0) {
        fprintf(stderr, "Ошибка: флаг -k должен стоять после всех выражений\n");
        return 1;
    }

    return 0;
}