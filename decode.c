#include <stdio.h>

#include "decode.h"

// Вычисление идет по таблице ASCII - в ней лежит сооветсвие чисел символам.
// answers - набор результатов вычисления троек
// count - число результатов
// answers[i] - key - это требование вычисления из текста задачи

// | № | Аргументы тройки | Выражение | Ответ | `- key (2)` | ASCII | Символ |
// |---|------------------|-----------|-------|-------------|-------|--------|
// | 1 | `41 + 33`        | 41 + 33   | 74    | 72          | 72    | `H`    |
// | 2 | `111 - 8`        | 111 - 8   | 103   | 101         | 101   | `e`    |
// | 3 | `22 '*' 5`       | 22 * 5    | 110   | 108         | 108   | `l`    |
// | 4 | `221 % 111`      | 221 % 111 | 110   | 108         | 108   | `l`    |
// | 5 | `100 + 13`       | 100 + 13  | 113   | 111         | 111   | `o`    |

void decode(const int *answers, int count, int key, char *text)
{
    for (int i = 0; i < count; i++) {
        text[i] = (char)(answers[i] - key);
    }
    // Добавляем последний элемент для обозначения конца строки
    text[count] = '\0'; 
}

void print_results(const int *answers, int count, const char *text)
{
    // Печатаем результаты вычисления троке
    for (int i = 0; i < count; i++) {
        printf("Ответ №%d: %d\n", i + 1, answers[i]);
    }
    // Текстровая строка после декодирования
    printf("Результирующая строка: %s\n", text);
}